// Exports the grocery catalog from src/data/mockData.ts into
//   db/catalog.json  – plain JSON (useful for inspection / other tools)
//   db/seed.sql      – D1-ready INSERT statements (categories + products)
// Run from artifacts/zyphix:  node scripts/catalog/export-mockdata.mjs
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import path from 'node:path';

const root = path.resolve(import.meta.dirname, '..', '..');
const src = readFileSync(path.join(root, 'src/data/mockData.ts'), 'utf8');

function readArray(exportName) {
  const at = src.indexOf(`export const ${exportName} = [`);
  if (at < 0) throw new Error(`${exportName} not found`);
  const open = src.indexOf('[', at);
  const close = src.indexOf('];', open) + 1;
  return new Function('return ' + src.slice(open, close))();
}

const products = readArray('products');
const categories = readArray('GROCERY_CATEGORIES');

const q = (v) => (v === null || v === undefined ? 'NULL' : `'${String(v).replace(/'/g, "''")}'`);
const n = (v) => (v === null || v === undefined ? 'NULL' : Number(v));

const isProduce = (p) => p.brand === 'Local Farm' || p.category === 'Fruits & Veg';
const isPlaceholder = (url) => /placehold\.co/.test(url || '');

const lines = [];
lines.push('-- generated by scripts/catalog/export-mockdata.mjs');
lines.push('DELETE FROM products; DELETE FROM categories;');
categories.forEach((c, i) => {
  lines.push(`INSERT INTO categories (name, icon, color, image_url, sort) VALUES (${q(c.name)}, ${q(c.icon)}, ${q(c.color)}, ${q(c.image)}, ${i});`);
});
for (const p of products) {
  const status = isPlaceholder(p.image) ? 'pending' : 'ready';
  const source = isPlaceholder(p.image) ? null : 'unsplash';
  const kind = isProduce(p) ? 'produce' : 'packaged';
  lines.push(
    `INSERT INTO products (id, name, brand, price, orig_price, category, weight, image_url, image_source, image_status, image_kind, tag, store_name, distance) VALUES (` +
      [q(p.id), q(p.name), q(p.brand), n(p.price), n(p.origPrice), q(p.category), q(p.weight), q(isPlaceholder(p.image) ? null : p.image), q(source), q(status), q(kind), q(p.tag), q(p.storeName), q(p.distance)].join(', ') +
      ');'
  );
}

mkdirSync(path.join(root, 'db'), { recursive: true });
writeFileSync(path.join(root, 'db/catalog.json'), JSON.stringify({ categories, products }, null, 0));
writeFileSync(path.join(root, 'db/seed.sql'), lines.join('\n') + '\n');
console.log(`exported ${products.length} products, ${categories.length} categories → db/seed.sql`);
